def generate_data(
    news_json_paths,
    sample_number=3,  # 每個語意類別『期望』生成的數量
    output_path="generated_data.json"
):
    all_news = []

    # 讀取所有來源檔案
    for path in news_json_paths:
        if Path(path).exists():
            with open(path, "r", encoding="utf-8") as f:
                data = json.load(f)
                # 確保有 summary 且排除廣告
                valid_data = [item for item in data if item.get("summary") and not item.get("is_ad", False)]
                all_news.extend(valid_data)
        else:
            print(f"⚠️ 找不到檔案: {path}")

    if not all_news:
        print("❌ 沒有可用的新聞資料，程式結束。")
        return

    print(f"📦 總共載入 {len(all_news)} 筆有效新聞資料。")

    # ==========================================
    # 階段 1：建立資源池 (分門別類整理庫存)
    # ==========================================
    news_pool = defaultdict(list)
    for item in all_news:
        news_pool[item["category"]].append(item)
        
    # 打亂每個類別的庫存，避免每次都抽到前面的新聞
    for cat in news_pool:
        random.shuffle(news_pool[cat])
        
    print("\n📊 目前庫存盤點：")
    for cat, items in news_pool.items():
        print(f"  - {cat}: {len(items)} 筆")

    # 定義各特徵的合法類別清單
    CATEGORY_LIST = {
        "煽動性": ["政治", "財經", "國際", "科技"],
        # "主觀": ["政治", "國際", "娛樂"],
        # "偏頗": ["政治", "財經", "國際"],
        # "語意誇大與聳動": ["政治", "財經", "國際", "科技", "娛樂"]
    }

    # ==========================================
    # 階段 2：輪詢發牌分配 (Round-Robin Allocation)
    # ==========================================
    allocated_tasks = {tbm: [] for tbm in TBM_PROMPT_MAP.keys()}
    
    # 開始一輪一輪發牌
    for _ in range(sample_number):
        for tbm_class in TBM_PROMPT_MAP.keys():
            valid_categories = CATEGORY_LIST.get(tbm_class, [])
            
            # 找出該 tbm_class 允許的類別中，還有庫存的類別
            available_cats = [c for c in valid_categories if len(news_pool[c]) > 0]
            
            if available_cats:
                # 隨機選一個還有庫存的合法類別
                chosen_cat = random.choice(available_cats)
                # 從庫存中 pop 出來 (保證文章互斥，不會重複生成)
                allocated_tasks[tbm_class].append(news_pool[chosen_cat].pop())

    # 顯示分配結果報告
    print("\n📝 任務分配完畢報告：")
    for tbm_class, tasks in allocated_tasks.items():
        cat_counts = defaultdict(int)
        for t in tasks:
            cat_counts[t["category"]] += 1
        cat_details = ", ".join([f"{k}:{v}" for k, v in cat_counts.items()])
        print(f"  - {tbm_class}: 共分配 {len(tasks)} 筆 ({cat_details})")

    # ==========================================
    # 階段 3：開始安全呼叫 API 生成
    # ==========================================
    results = []
    print("\n🚀 開始呼叫 LLM 進行生成...")
    
    TEMPERATURE_LIST = {"煽動性": 0.75, "主觀": 0.75, "偏頗": 0.75, "語意誇大與聳動": 0.75}
    REPEAT_PENALTY_LIST = {"煽動性": 1.25, "主觀": 1.2, "偏頗": 1.2, "語意誇大與聳動": 1.2}

    for tbm_class, tasks in allocated_tasks.items():
        if not tasks:
            print(f"⚠️ {tbm_class} 沒有分配到任何任務，跳過。")
            continue
            
        print(f"\n--- 正在處理類別: {tbm_class} ({len(tasks)} 筆) ---")
        specific_prompt = TBM_PROMPT_MAP[tbm_class]
        temp = TEMPERATURE_LIST.get(tbm_class, 0.7)
        penalty = REPEAT_PENALTY_LIST.get(tbm_class, 1.2)
        
        print(f"使用設定 - 溫度: {temp}, 重複懲罰: {penalty}")

        for item in tasks:
            prompt = NEW_PROMPT.format(
                tbm_class=tbm_class,
                specific_prompt=specific_prompt,
                summary=item["summary"]
            )
            try:
                rewritten = call_llm(prompt, temp, penalty)
                rewritten = rewritten.strip().strip('"').strip('「').strip('」')

                results.append({
                    "id": item.get("id", ""),
                    "category": item["category"],
                    "title": item.get("title", ""),
                    "content": rewritten,
                    "label": 1,
                    "tbm_class": tbm_class,
                    "original_summary": item["summary"]
                })
                print(f"✅ {tbm_class} | {item['category']} | ID: {item.get('id')} | 生成成功")
                
                # 即時存檔
                with open(output_path, "w", encoding="utf-8") as f:
                    json.dump(results, f, ensure_ascii=False, indent=2)
                    
            except Exception as e:
                print(f"❌ [ERROR] {tbm_class} - ID {item.get('id')}: {e}")

    print(f"\n🎉 全部生成完成，共成功 {len(results)} 筆，輸出至 {output_path}")

