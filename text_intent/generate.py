def call_llm(prompt: str, temperature, repeat_penalty) -> str:
    payload = {
        "model": MODEL_NAME,
        "prompt": prompt,
        "stream": False, 
        "options": {
            "temperature": temperature,       # [修正] 降低溫度，減少幻覺與隨機性
            "repeat_penalty": repeat_penalty,   # [新增] 抑制重複/跳針 (關鍵！)
            # "top_k": 40             # 可選，視模型支援程度
        }
    }
    response = requests.post(
        url,
        json=payload,
        auth=(username, password),
        timeout=600
    )
    response.raise_for_status()
    return response.json()["response"]

